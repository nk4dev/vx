'use strict';
// Compiles contracts/VXCollection.sol and writes src/nft/collection.ts, the
// ABI + bytecode that `vx3 mint nft` deploys when no contract is given.
// Re-run with `bun run build:nft-artifact` after editing the contract.

const fs = require('node:fs');
const path = require('node:path');
const solc = require('solc');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'contracts', 'VXCollection.sol');
const outPath = path.join(root, 'src', 'nft', 'collection.ts');

const input = {
  language: 'Solidity',
  sources: {
    'VXCollection.sol': { content: fs.readFileSync(sourcePath, 'utf-8') },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    // No PUSH0 / MCOPY, so the bytecode also deploys on chains that lag
    // behind mainnet's EVM version.
    evmVersion: 'paris',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length > 0) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

const contract = output.contracts['VXCollection.sol'].VXCollection;
const file = `// GENERATED by scripts/build-nft-artifact.cjs from contracts/VXCollection.sol
// (solc ${solc.version()}, evmVersion paris). Do not edit by hand.

export const COLLECTION_ABI = ${JSON.stringify(contract.abi, null, 2)} as const;

export const COLLECTION_BYTECODE =
  '0x${contract.evm.bytecode.object}';
`;
fs.writeFileSync(outPath, file);
console.log(`Wrote ${path.relative(root, outPath)}`);
